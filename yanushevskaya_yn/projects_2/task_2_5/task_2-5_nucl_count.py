dna = input("Введите последовательность ДНК: ").upper()
count_A = dna.count('A')
count_T = dna.count('T')
count_C = dna.count('C')
count_G = dna.count('G')

len(dna)

# all = {count_A + count_T + count_C + count_G}
# pr_ = (count_A / all) * 100
# Возможно печатать {len(dna)} проще и правильнее,
# но если в последовательности будет содержаться какой-либо артефакт,
# то {len(dna)} посчитает процент вместе с этим артефактом

pr_A = (count_A / len(dna)) * 100
pr_T = (count_T / len(dna)) * 100
pr_C = (count_C / len(dna)) * 100
pr_G = (count_G / len(dna)) * 100


print('=== Анализ последовательности ДНК ===\n'
      f'Подсчёт нуклеотидов:\n'
      f'Аденин: {count_A}\n'
      f'Тимин: {count_T}\n'
      f'Гуанин: {count_G}\n'
      f'Цитозин: {count_C}\n'
      # f'Количество нуклеотидов: {count_A + count_T + count_C + count_G}'
    
      f'{len(dna)} \n'
      f'Подсчёт процентного содержания:\n'
      f'Аденин: {pr_A:.2f} %\n'
      f'Тимин: {pr_T:.2f} %\n'
      f'Гуанин: {pr_G:.2f} %\n'
      f'Цитозин: {pr_C:.2f} %\n')

