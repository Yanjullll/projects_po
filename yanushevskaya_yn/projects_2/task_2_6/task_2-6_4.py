print("Подъезжает Илья к трём дорожкам, на перекрёстке камень лежит,\nА на том камне написано: \n"
      "«Кто вправо поедет — тому убитым быть,\n"
      "Кто влево поедет — тому богатым быть, \n"
      "А кто прямо поедет — тому женатым быть»\n")

choice = input("Куда ехать? (направо / налево / прямо): \n").strip().lower()

if choice in ("направо", "право", "вправо"):
    print("Напали сорок разбойников.\n"
    "Илья половину положил, остальные сбежали.\n"
    "Вернулся к камню, стёр надпись: «Ездил направо — убит не был»")

elif choice in ("прямо", "вперёд", "вперед"):
    print("Королевична заманила в терем, а там ловушка Джокера,\n"
    "Илья сбросил её в погреб, освободил сорок богатырей.\n"
    "Вернулся к камню, стёр надпись: «Прямо ездил — женатым не бывал»")

elif choice in ("налево", "лево", "влево"):
    print("На дороге камень в триста пудов. Илья свернул его — под ним клад.\n"
    "Построил три церкви в Киеве, остальное раздал\n"
    "Вернулся к камню, стёр надпись: «Влево ездил — богат не бывал!»")

else:
    print("Задумался Илья и остался стоять у камня")